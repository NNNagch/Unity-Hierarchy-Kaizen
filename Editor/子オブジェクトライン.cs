using UnityEngine;
using UnityEditor;

[InitializeOnLoad] // エディター起動時に自動で初期化する属性
public class 階層ライン描画
{
    // 静的コンストラクタで、ヒエラルキーウィンドウの描画イベントにコールバックを登録する
    static 階層ライン描画()
    {
        // ヒエラルキーウィンドウの各アイテム描画時に階層描画メソッドを呼び出すように登録する
        EditorApplication.hierarchyWindowItemOnGUI += 階層描画;
    }

    // ヒエラルキーウィンドウの各アイテム描画時に呼ばれるコールバック
    static void 階層描画(int _識別番号, Rect _矩形)
    {
        // _識別番号から対応するゲームオブジェクトを取得する
        GameObject _オブジェクト = EditorUtility.InstanceIDToObject(_識別番号) as GameObject;
        if (_オブジェクト == null)
            return;

        // 階層レベルが1（ルートオブジェクト）の場合はラインを描画しない
        if (_オブジェクト.transform.parent == null)
            return;

        // ライン描画用の各色を定義する
        Color _上線色   = new Color(0.64f, 0.64f, 0.64f, 0.00000000000000003f); // 上面の水平ラインの色
        
        Color _底面色   = new Color(0.64f, 0.64f, 0.64f, 0.0f); // 底面の水平ラインの色


        Color _左たて   = new Color(1f, 1f, 1f, 1f); // 左側の垂直ラインの色

        Color _左たて2   = new Color(1f, 1f, 1f, 0.0f); // 左側の垂直ラインの色

        Color _上よこ１   = new Color(1f, 1f, 1f, 0f); // 左側の垂直ラインの色
        

        Color _０   = new Color(0.64f, 0.64f, 0.64f, 0.0f); // 左側の垂直ラインの色

        // 現在のGUIの色を保持する
        Color _元の色 = GUI.color;

        // ヒエラルキーウィンドウの右端の位置を取得する
        float _右端 = EditorGUIUtility.currentViewWidth;
        // ラインの左端は、オブジェクトの表示位置の左端に合わせる（_矩形.x）
        float _左端 = _矩形.x;

        // -----------------------------------------------------------
        // 底面の水平ライン描画（1pxのライン）
        // 修正点:
        //   ・幅を13pxに設定
        //   ・オブジェクトの左端から13pxの位置に配置
        //   ・さらにX方向に+1pxのオフセットを追加
        // -----------------------------------------------------------
        GUI.color = _底面色; // GUIの色を底面の色に設定する
        // オブジェクトの左端から13px＋1pxオフセットの位置に配置 → _左端 + 1 としている
        // ラインの幅は13px, 高さは1px
        Rect _底面矩形 = new Rect(_左端 -1, _矩形.y + _矩形.height - 1, 13, 1);
        // 定義した矩形に対してラインを描画する
        EditorGUI.DrawRect(_底面矩形, _底面色);

        // -----------------------------------------------------------
        // 上面の水平ライン描画（1pxのライン）
        // -----------------------------------------------------------
        GUI.color = _上線色; // GUIの色を上面の色に設定する
        // オブジェクトの上面に合わせた矩形を定義する（高さ1px）
        Rect _上面矩形 = new Rect(_左端, _矩形.y - 0, _右端 - _左端, 1);
        // 定義した矩形に対してラインを描画する
        EditorGUI.DrawRect(_上面矩形, _上線色);

        
        GUI.color = _左たて; // GUIの色を上面の色に設定する
        // オブジェクトの上面に合わせた矩形を定義する（高さ1px）
        Rect _上面矩形2 = new Rect(_左端 -2, _矩形.y - 1, _右端 - _左端, 1);
        // 定義した矩形に対してラインを描画する
        EditorGUI.DrawRect(_上面矩形2, _上よこ１);
        

                // -----------------------------------------------------------
        // 左側の垂直ライン描画（幅1pxのライン）
        // -----------------------------------------------------------
        
        // オブジェクトの左端から-3pxの位置に1pxのラインを定義する
        Rect _左垂直矩形 = new Rect(_矩形.x - 3, _矩形.y, 1, _矩形.height);
        // 定義した矩形に対してラインを描画する
        EditorGUI.DrawRect(_左垂直矩形, _左たて2);


        
        // -----------------------------------------------------------
        // 左側の垂直ラインの右側に1pxずらした位置に同じ垂直ラインを描画する
        // -----------------------------------------------------------
        // 1pxずらした位置：_矩形.x -3 + 1 = _矩形.x -2
        Rect _左垂直矩形2 = new Rect(_矩形.x - 2, _矩形.y, 1, _矩形.height);
        // 定義した矩形に対してラインを描画する
        EditorGUI.DrawRect(_左垂直矩形2, _０);

        // GUIの色を元の状態に戻す
        GUI.color = _元の色;







    }
}
